#!/usr/bin/env python3
"""Fills in mikrotik/nibe-hub.yaml with .env and the MCP server's TLS files.

    python3 tools/make_app_yaml.py --cert cert.pem --key key.pem [--env .env]
        [--image ghcr.io/<you>/nibe-hub:latest] [--out mikrotik/nibe-hub-local.yaml]

The output contains the pump password, the MCP token and the TLS key: it is written with
mode 0600 and is git-ignored. Each service gets only its own settings, as with
tools/run_local.sh: the collector the NIBE_* lines, the MCP server the MCP_* lines and TZ_NAME.
"""
import argparse, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATE = os.path.join(ROOT, "mikrotik", "nibe-hub.yaml")

ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
ap.add_argument("--env", default=os.path.join(ROOT, ".env"))
ap.add_argument("--cert", required=True, help="PEM certificate for the MCP server (its SAN must contain the app's IP)")
ap.add_argument("--key", required=True, help="PEM private key for --cert")
ap.add_argument("--image", default="ghcr.io/kkerssem/nibe-hub:latest")
ap.add_argument("--out", default=os.path.join(ROOT, "mikrotik", "nibe-hub-local.yaml"))
args = ap.parse_args()


def fail(msg):
    sys.exit(f"error: {msg}")


env = {}
with open(args.env, newline="") as f:
    for line in f.read().replace("\r", "").split("\n"):
        if not line.strip() or line.lstrip().startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        env[k.strip()] = v

for k in ["NIBE_URL", "NIBE_USER", "NIBE_PASS", "NIBE_TLS_FINGERPRINT", "MCP_TOKEN"]:
    if not env.get(k, "").strip() or "<" in env[k]:
        fail(f"{k} is empty or still a placeholder in {args.env}")

# Values the template sets itself (database path, log format, MCP address and TLS files).
FIXED = {"DB_PATH", "LOG_TIMESTAMPS", "MCP_BIND", "MCP_TLS_CERT", "MCP_TLS_KEY"}
for k in sorted(FIXED & env.keys()):
    print(f"note: {k} from {args.env} is ignored; the app sets it", file=sys.stderr)

collector = {k: v for k, v in env.items() if (re.fullmatch(r"NIBE_[A-Z_]+", k) or k == "RUST_LOG") and v != ""}
mcp = {k: v for k, v in env.items() if (re.fullmatch(r"MCP_[A-Z_]+", k) or k in ("TZ_NAME", "RUST_LOG")) and k not in FIXED and v != ""}

# RouterOS replaces [name] placeholders such as [secret:x] or [env:x] in environment values.
for k, v in {**collector, **mcp}.items():
    if "[" in v:
        print(f"warning: {k} contains '['; RouterOS may treat [...] as a placeholder", file=sys.stderr)


def env_block(d):
    # JSON strings are valid YAML double-quoted scalars, so any value is quoted safely.
    return "\n".join(f"      {k}: {json.dumps(v)}" for k, v in d.items())


def pem_block(path, kind):
    with open(path) as f:
        text = f.read().replace("\r", "").strip()
    if f"-----BEGIN {kind}" not in text and not (kind == "PRIVATE KEY" and re.search(r"-----BEGIN [A-Z ]*PRIVATE KEY-----", text)):
        fail(f"{path} does not look like a PEM {kind.lower()}")
    if "ENCRYPTED" in text:
        fail(f"{path} is encrypted; the MCP server needs an unencrypted key")
    return "\n".join("      " + line for line in text.split("\n"))


cert = pem_block(args.cert, "CERTIFICATE")
key = pem_block(args.key, "PRIVATE KEY")

with open(TEMPLATE) as f:
    lines = f.read().split("\n")

# The template is a working app definition with empty values. Replace the image, the two
# placeholder lines in the TLS configs, and each service's environment: the keys the template
# fixes are kept, the rest (with their comments) is replaced by this service's .env lines.
generated = {"collector": collector, "mcp": mcp}
placeholders = {"replace this line with the PEM certificate": cert, "replace this line with the PEM private key": key}
out, service, i, seen = [], None, 0, set()
while i < len(lines):
    line = lines[i]
    m = re.fullmatch(r"  (\w[\w-]*):", line)
    if m:
        service = m.group(1)
    if re.fullmatch(r"    image: .*", line):
        line = f"    image: {args.image}"
    for prefix, block in placeholders.items():
        if line.strip().startswith(prefix):
            line = block
            seen.add(prefix)
    out.append(line)
    i += 1
    if line == "    environment:" and service in generated:
        fixed = []
        while i < len(lines) and lines[i].startswith("      "):
            k = lines[i].strip().split(":", 1)[0]
            if k in FIXED:
                fixed.append(lines[i])
            i += 1
        out += fixed
        if generated[service]:
            out.append(env_block(generated[service]))
        seen.add(service)
missing = (set(placeholders) | set(generated)) - seen
if missing:
    fail(f"{TEMPLATE} no longer has the expected structure (not found: {', '.join(sorted(missing))})")
out = "\n".join(out)
# The header explains the template; the filled-in file says what it is instead.
out = re.sub(r"\A(#.*\n)+\n", "# nibe-hub MikroTik App, generated by tools/make_app_yaml.py. Contains secrets: do not commit.\n\n", out)

fd = os.open(args.out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write(out)
os.chmod(args.out, 0o600)

# Show which addresses the certificate is valid for, so a mismatch with the app's IP is spotted now.
try:
    text = subprocess.run(["openssl", "x509", "-in", args.cert, "-noout", "-text"], capture_output=True, text=True, check=True).stdout
    sans = re.findall(r"(?:IP Address|DNS):[^,\n]+", text)
    print(f"certificate is valid for: {', '.join(s.strip() for s in sans) or 'no subjectAltName (clients will reject it)'}", file=sys.stderr)
except Exception:
    pass
print(f"wrote {args.out}: collector gets {sorted(collector)}, mcp gets {sorted(mcp)}", file=sys.stderr)
